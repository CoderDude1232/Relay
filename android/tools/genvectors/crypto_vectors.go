package main

import (
	"crypto/aes"
	"crypto/cipher"
	"crypto/ecdsa"
	"crypto/elliptic"
	"crypto/rand"
	"crypto/sha256"
	"crypto/sha512"
	"encoding/base64"
	"strconv"
	"strings"

	"github.com/gtank/ristretto255"
)

// Crypto vectors for the Android client's Stage 2 tests.
//
// IMPORTANT — why the OPRF is reimplemented here rather than imported:
// the server's implementation lives in server/internal/oprf, and Go's `internal`
// rule makes it importable only from within the github.com/relayapp/relay-server
// module. This tool is a separate module precisely so that generating vectors
// never modifies ../../../server. The ~15 lines below are therefore transcribed
// from internal/oprf/oprf.go and use the SAME library the server uses
// (gtank/ristretto255), so they still cross-check the parts that actually differ
// between implementations: ristretto255 encodings, SHA-512 -> from_hash mapping,
// the domain tags, and the hash input ordering.
//
// A vector generated by importing the server's own code would be strictly
// better. That needs either the generator moved into server/ or internal/oprf
// exported — an owner decision, since both touch the shared server module.
//
// The attachment vector below has no such caveat: it uses only Go's standard
// library, so it is an independent check of the nonce||ciphertext||tag layout.

const (
	oprfHashToGroupDomain = "Relay-OPRF-v1-h2g"
	oprfTokenDomain       = "Relay-OPRF-v1-token"
)

// oprfNormalize mirrors internal/oprf.Normalize.
func oprfNormalize(identifier string) string {
	return strings.ToLower(strings.TrimSpace(identifier))
}

// oprfHashToGroup mirrors internal/oprf.hashToGroup.
func oprfHashToGroup(x []byte) *ristretto255.Element {
	h := sha512.New()
	h.Write([]byte(oprfHashToGroupDomain))
	h.Write(x)
	return ristretto255.NewElement().FromUniformBytes(h.Sum(nil))
}

// oprfToken mirrors internal/oprf.Key.Token.
func oprfToken(k *ristretto255.Scalar, identifier string) []byte {
	x := []byte(oprfNormalize(identifier))
	n := ristretto255.NewElement().ScalarMult(k, oprfHashToGroup(x))
	h := sha256.New()
	h.Write([]byte(oprfTokenDomain))
	h.Write(x)
	h.Write(n.Encode(nil))
	return h.Sum(nil)
}

// paddingTarget mirrors RelayCore/ContentPadding.swift targetSize(for:).
func paddingTarget(size int) int {
	for _, bucket := range []int{256, 512, 1024, 4096} {
		if bucket > size {
			return bucket
		}
	}
	return ((size / 4096) + 1) * 4096
}

func b64(b []byte) string { return base64.StdEncoding.EncodeToString(b) }

func cryptoVectors() map[string]any {
	// --- OPRF ------------------------------------------------------------
	var seed [64]byte
	if _, err := rand.Read(seed[:]); err != nil {
		panic(err)
	}
	key := ristretto255.NewScalar().FromUniformBytes(seed[:])

	type oprfCase struct {
		Identifier string `json:"identifier"`
		Normalized string `json:"normalized"`
		Token      string `json:"token"`
	}
	var oprfCases []oprfCase
	for _, id := range []string{
		"alice",
		"  Alice  ",       // normalization: trim + lowercase
		"BOB.SMITH_99",    // the username charset the server allows
		"user@example.com", // discovery also covers emails
		"ünïcödé",         // multi-byte identifiers must hash identically
	} {
		oprfCases = append(oprfCases, oprfCase{
			Identifier: id,
			Normalized: oprfNormalize(id),
			Token:      b64(oprfToken(key, id)),
		})
	}

	// --- Attachment blob --------------------------------------------------
	plaintext := []byte("relay attachment interop ✓ payload")
	aesKey := make([]byte, 32)
	nonce := make([]byte, 12)
	if _, err := rand.Read(aesKey); err != nil {
		panic(err)
	}
	if _, err := rand.Read(nonce); err != nil {
		panic(err)
	}
	block, err := aes.NewCipher(aesKey)
	if err != nil {
		panic(err)
	}
	gcm, err := cipher.NewGCM(block)
	if err != nil {
		panic(err)
	}
	sealed := gcm.Seal(nil, nonce, plaintext, nil) // ciphertext || tag
	blob := append(append([]byte{}, nonce...), sealed...)
	digest := sha256.Sum256(blob)

	// --- Padding ----------------------------------------------------------
	type paddingCase struct {
		Input  int `json:"input"`
		Target int `json:"target"`
	}
	var paddingCases []paddingCase
	for _, n := range []int{0, 1, 255, 256, 257, 511, 512, 1023, 1024, 4095, 4096, 4097, 8191, 8192, 20000} {
		paddingCases = append(paddingCases, paddingCase{Input: n, Target: paddingTarget(n)})
	}

	// --- Relay-Sig request auth -------------------------------------------
	// Mirrors server/internal/api/sigauth.go. Android is the first client to
	// implement this scheme, so these vectors pin the canonical string, the
	// digest, and the ASN.1/DER signature encoding the Go verifier accepts.
	// NOTE the path excludes the query string: the server signs r.URL.Path.
	authKey, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		panic(err)
	}
	type authCase struct {
		Method      string `json:"method"`
		Path        string `json:"path"`
		TimestampMs int64  `json:"timestampMs"`
		Nonce       string `json:"nonce"`
		Canonical   string `json:"canonical"`
		Digest      string `json:"digest"`
		Signature   string `json:"signature"`
	}
	var authCases []authCase
	for _, c := range []struct {
		method, path, nonce string
		ts                  int64
	}{
		{"GET", "/v1/queue", "bm9uY2UtMQ==", 1758000000000},
		{"PUT", "/v1/keys", "bm9uY2UtMg==", 1758000000001},
		// A path that would carry a query string in the real request: only the
		// path is signed, so ?device=3 must NOT appear here.
		{"GET", "/v1/keys/6f1a2b3c-4d5e-4f60-8899-aabbccddeeff", "bm9uY2UtMw==", 1758000000002},
		{"POST", "/v1/messages/ack", "bm9uY2UtNA==", 1758000000003},
	} {
		canonical := c.method + "\n" + c.path + "\n" +
			strconv.FormatInt(c.ts, 10) + "\n" + c.nonce
		digest := sha256.Sum256([]byte(canonical))
		sig, err := ecdsa.SignASN1(rand.Reader, authKey, digest[:])
		if err != nil {
			panic(err)
		}
		authCases = append(authCases, authCase{
			Method: c.method, Path: c.path, TimestampMs: c.ts, Nonce: c.nonce,
			Canonical: canonical,
			Digest:    b64(digest[:]),
			Signature: b64(sig),
		})
	}

	return map[string]any{
		"_comment": "GENERATED FILE -- do not edit. Produced by android/tools/genvectors -kind=crypto. " +
			"The OPRF section is transcribed from server/internal/oprf (Go's internal rule blocks importing it); " +
			"the attachment section uses only the Go standard library.",
		"oprf": map[string]any{
			"hashToGroupDomain": oprfHashToGroupDomain,
			"tokenDomain":       oprfTokenDomain,
			"keyScalar":         b64(key.Encode(nil)),
			"cases":             oprfCases,
		},
		"attachment": map[string]any{
			"_comment":  "AES-256-GCM. blob is nonce(12) || ciphertext || tag(16); digest is SHA-256 OF THE BLOB.",
			"key":       b64(aesKey),
			"blob":      b64(blob),
			"digest":    b64(digest[:]),
			"plaintext": b64(plaintext),
		},
		"relaySig": map[string]any{
			"_comment": "Canonical string is METHOD \\n PATH \\n TIMESTAMP \\n NONCE; the path " +
				"excludes the query string. Signature is ECDSA-P256 ASN.1/DER over SHA-256 of it.",
			"publicKey": b64(elliptic.Marshal(elliptic.P256(), authKey.X, authKey.Y)),
			"cases":     authCases,
		},
		"padding": map[string]any{
			"buckets": []int{256, 512, 1024, 4096},
			"cases":   paddingCases,
		},
	}
}
